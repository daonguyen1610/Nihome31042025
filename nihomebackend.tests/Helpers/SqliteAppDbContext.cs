using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ChangeTracking;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.ValueGeneration;
using NihomeBackend.Data;

namespace nihomebackend.tests.Helpers;

/// <summary>
/// Test-only AppDbContext for the SQLite in-memory provider.
///
/// The production model declares SQL Server column types (<c>nvarchar(max)</c>,
/// <c>decimal(18,2)</c>, ...) and T-SQL filtered indexes, which SQLite cannot
/// create. Services that use set-based operations need a relational provider,
/// so this context drops the provider-specific type strings and index filters
/// before SQLite generates its schema. Queries and behaviour stay identical to
/// the production model.
/// </summary>
public sealed class SqliteAppDbContext(DbContextOptions<AppDbContext> options) : AppDbContext(options)
{
    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        base.OnModelCreating(modelBuilder);

        foreach (var entityType in modelBuilder.Model.GetEntityTypes())
        {
            foreach (var property in entityType.GetProperties())
            {
                property.SetColumnType((string?)null);

                // SQL Server generates rowversion values itself; SQLite has no
                // equivalent, so the test provider stores client-generated bytes.
                // Leaving the property store-generated makes EF omit the column
                // from INSERT, which then fails the NOT NULL constraint.
                if (property.ClrType == typeof(byte[]) && property.IsConcurrencyToken)
                {
                    property.ValueGenerated = ValueGenerated.Never;
                    property.SetValueGeneratorFactory((_, _) => new TestRowVersionGenerator());
                }
            }

            foreach (var index in entityType.GetIndexes())
                index.SetFilter(null);
        }
    }

    private sealed class TestRowVersionGenerator : ValueGenerator<byte[]>
    {
        public override bool GeneratesTemporaryValues => false;

        public override byte[] Next(EntityEntry entry)
        {
            var bytes = new byte[8];
            Random.Shared.NextBytes(bytes);
            return bytes;
        }
    }
}
